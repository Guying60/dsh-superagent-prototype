export interface RateLimiterFeatures {
  /** EDGE-001: constructor precondition guard */
  rangeGuard: boolean;
  /** EDGE-002: consume() rejects non-positive amounts */
  validateConsume: boolean;
  /** EDGE-003: getAvailableTokens() returns an integer */
  integerTokens: boolean;
  /** SEC-003: consume() rejects NaN / Infinity */
  finiteGuard: boolean;
  /** REV-001: invariants documented next to the implementation */
  invariantsDoc: boolean;
  /** DIST-001: distributed reconciliation hook (deliberately not implemented) */
  clusterReconcile: boolean;
}

export const BASE_FEATURES: RateLimiterFeatures = {
  rangeGuard: false,
  validateConsume: false,
  integerTokens: false,
  finiteGuard: false,
  invariantsDoc: false,
  clusterReconcile: false
};

export const FULLY_FIXED: RateLimiterFeatures = {
  rangeGuard: true,
  validateConsume: true,
  integerTokens: true,
  finiteGuard: true,
  invariantsDoc: true,
  clusterReconcile: false
};

/** Which repair strategy each rule id unlocks. This is the fix space. */
export const FIX_BY_RULE: Record<string, keyof RateLimiterFeatures> = {
  'EDGE-001': 'rangeGuard',
  'EDGE-002': 'validateConsume',
  'EDGE-003': 'integerTokens',
  'SEC-003': 'finiteGuard',
  'REV-001': 'invariantsDoc'
  // NOTE: DIST-001 is intentionally absent — no strategy exists in this fix space.
};

/** Repair directives, used by the critic to explain *why* a rule blocks convergence. */
const RULE_DIRECTIVES: Record<string, string> = {
  'EDGE-001': 'add a constructor precondition guard rejecting non-finite / non-positive capacity and refill rate',
  'EDGE-002': 'reject non-positive token amounts in consume() instead of inflating the bucket',
  'EDGE-003': 'floor the value returned by getAvailableTokens() so fractional refill never leaks out',
  'SEC-003': 'validate Number.isFinite(tokens) before mutating state',
  'REV-001': 'document the class invariants next to the implementation',
  'SEC-001': 'remove dynamic code execution entirely',
  'DIST-001': 'a distributed reconciliation hook cannot be produced by this agent offline'
};

export function asCode(output: any): string {
  if (typeof output === 'string') return output;
  if (output && typeof output === 'object') {
    return String(output.code ?? output.source ?? output.artifact ?? '');
  }
  return '';
}

/**
 * Simulated model latency per agent turn.
 *
 * The platform runs fully offline and deterministically; this delay stands in for an LLM
 * round-trip so that the scheduler's queueing / load-balancing behaviour is *observable*
 * instead of instantaneous. It is a simulation, and it is labelled as one — set it to 0
 * to measure pure engine overhead.
 */
export const SIMULATED_LLM_LATENCY_MS = Number(
  process.env.AETHER_SIM_LATENCY_MS ?? 55
);

const latency = () =>
  SIMULATED_LLM_LATENCY_MS > 0
    ? new Promise<void>(r => setTimeout(r, SIMULATED_LLM_LATENCY_MS))
    : Promise.resolve();

export function renderRateLimiter(f: RateLimiterFeatures): string {
  const l: string[] = [];
  l.push('/**');
  l.push(' * Token Bucket RateLimiter — generated by the Developer agent (Alex).');
  if (f.invariantsDoc) {
    l.push(' *');
    l.push(' * Invariant: 0 <= tokens <= capacity holds after every public call.');
    l.push(' * Invariant: refill is lazy and monotone; tokens never overshoot capacity.');
  }
  l.push(' */');
  l.push('class RateLimiter {');
  l.push('  constructor(capacity, refillRatePerSec) {');

  if (f.rangeGuard) {
    l.push('    if (typeof capacity !== "number" || !Number.isFinite(capacity) || capacity <= 0) {');
    l.push('      throw new RangeError("capacity must be a positive finite number");');
    l.push('    }');
    l.push('    if (typeof refillRatePerSec !== "number" || refillRatePerSec <= 0) {');
    l.push('      throw new RangeError("refillRatePerSec must be a positive number");');
    l.push('    }');
  }

  l.push('    this.capacity = capacity;');
  l.push('    this.refillRatePerSec = refillRatePerSec;');
  l.push('    this.tokens = capacity;');
  l.push('    this.lastRefill = Date.now();');

  if (f.clusterReconcile) {
    l.push('    this.clusterCounter = reconcileWithCluster(capacity);');
  }

  l.push('  }');
  l.push('');
  l.push('  _refill() {');
  l.push('    const now = Date.now();');
  l.push('    const deltaSec = (now - this.lastRefill) / 1000;');
  l.push('    this.tokens = Math.min(this.capacity, this.tokens + deltaSec * this.refillRatePerSec);');
  l.push('    this.lastRefill = now;');
  l.push('  }');
  l.push('');
  l.push('  consume(tokens) {');
  l.push('    if (tokens === undefined) { tokens = 1; }');

  if (f.validateConsume) {
    l.push('    if (typeof tokens !== "number" || tokens <= 0) {');
    l.push('      throw new RangeError("tokens must be a positive number");');
    l.push('    }');
  }
  if (f.finiteGuard) {
    l.push('    if (!Number.isFinite(tokens)) {');
    l.push('      throw new RangeError("tokens must be a finite number");');
    l.push('    }');
  }

  l.push('    this._refill();');
  l.push('    if (this.tokens >= tokens) {');
  l.push('      this.tokens -= tokens;');
  l.push('      return true;');
  l.push('    }');
  l.push('    return false;');
  l.push('  }');
  l.push('');
  l.push('  getAvailableTokens() {');
  l.push('    this._refill();');
  l.push(f.integerTokens ? '    return Math.floor(this.tokens);' : '    return this.tokens;');
  l.push('  }');
  l.push('');
  l.push('  reset() {');
  l.push('    this.tokens = this.capacity;');
  l.push('    this.lastRefill = Date.now();');
  l.push('  }');
  l.push('}');

  return l.join('\n');
}

