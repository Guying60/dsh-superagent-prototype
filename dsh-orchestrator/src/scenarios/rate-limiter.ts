export function makeVerificationSpec(opts: {
  auditors: string[];
  requireCluster: boolean;
  threshold?: number;
}): VerificationSpec {
  const rules: VerificationSpec['rules'] = [
    {
      id: 'SEC-001',
      name: 'no dynamic code execution',
      severity: 'critical',
      check: output => {
        const code = asCode(output);
        const bad = /(^|[^.\w])eval\s*\(/.test(code) || /new\s+Function\s*\(/.test(code);
        return {
          passed: !bad,
          message: bad ? 'eval()/new Function() found in the artifact' : 'no dynamic execution',
          score: bad ? 0 : 1
        };
      }
    },
    {
      id: 'IFACE-001',
      name: 'required public interface',
      severity: 'critical',
      check: output => {
        const code = asCode(output);
        const missing = ['consume(', 'getAvailableTokens(', 'reset('].filter(m => !code.includes(m));
        return {
          passed: missing.length === 0,
          message: missing.length === 0 ? 'all required methods present' : `missing ${missing.join(', ')}`,
          score: missing.length === 0 ? 1 : 0.4
        };
      }
    }
  ];

  if (opts.requireCluster) {
    rules.push({
      id: 'DIST-001',
      name: 'distributed counter reconciliation',
      severity: 'critical',
      check: output => {
        const code = asCode(output);
        const ok = code.includes('reconcileWithCluster(');
        return {
          passed: ok,
          message: ok
            ? 'distributed reconciliation hook present'
            : 'the artifact has no cluster reconciliation; a single-process token bucket cannot guarantee a global rate',
          score: ok ? 1 : 0
        };
      }
    });
  }

  return {
    rules,
    confidenceThreshold: opts.threshold ?? 0.9,
    executableSandboxCheck: {
      testScriptGenerator: (_output, ctx) => ctx?.requirementSpec?.testSuiteCode || RATE_LIMITER_TESTS,
      expectedExitCode: 0,
      timeoutMs: 3000
    },
    multiAgentVoting: {
      auditorAgentIds: opts.auditors,
      minPassRatio: 1
    }
  };
}

