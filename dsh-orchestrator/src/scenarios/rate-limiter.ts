class RequirementAnalystBrain implements AgentBrain {
  readonly kind = 'requirement_analyst';
  readonly name = 'Structured Requirement Extraction';

  public async think(ctx: BrainContext): Promise<BrainOutput> {
    await latency();
    const difficulty = (ctx.request.input.difficulty as TaskDifficulty) ?? 'normal';
    const seed = ctx.request.input.seedSource as string | undefined;

    const criteria =
      difficulty === 'hard'
        ? [
            'support capacity + refill rate configuration',
            'reject capacity <= 0 with RangeError',
            'reject non-positive consumption with RangeError',
            'return integer token counts',
            'reconcile the bucket with a cluster-wide counter (distributed mode)'
          ]
        : [
            'support capacity + refill rate configuration',
            'reject capacity <= 0 with RangeError',
            'reject non-positive consumption with RangeError',
            'return integer token counts',
            'document the state invariants'
          ];

    return {
      output: {
        featureName: 'Token Bucket RateLimiter',
        difficulty,
        acceptanceCriteria: criteria,
        securityConstraints: [
          'no eval()/new Function() in the artifact',
          'validate Number.isFinite(tokens) before mutating state'
        ],
        testSuiteCode: RATE_LIMITER_TESTS,
        seedBytes: seed?.length ?? 0
      },
      reasoning:
        `Parsed the request into ${criteria.length} acceptance criteria and generated a ` +
        `${RATE_LIMITER_TESTS.split('assert').length - 1}-assertion suite tagged with rule ids ` +
        `so failures are attributable to a single rule.`,
      confidence: 0.94,
      tokensUsed: estimateTokens(RATE_LIMITER_TESTS.slice(0, 400))
    };
  }
}

