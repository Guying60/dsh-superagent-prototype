/**
 * The repair brain. It never looks at the iteration number: it looks at which rule ids
 * are still failing and enables the corresponding strategy.
 */
class DeveloperBrain implements AgentBrain {
  readonly kind = 'developer';
  readonly name = 'Feedback-Driven Repair';

  public async think(ctx: BrainContext): Promise<BrainOutput> {
    await latency();
    const seed = (ctx.request.input.seedFeatures as RateLimiterFeatures) ?? BASE_FEATURES;
    const features: RateLimiterFeatures = { ...seed };    const applied: string[] = [];
    const unresolved: string[] = [];

    for (const failure of ctx.failedRules) {
      const id = failure.id;
      if (!id) continue;
      const strategy = FIX_BY_RULE[id];
      if (strategy) {
        if (!features[strategy]) {
          features[strategy] = true;
          applied.push(`${id} → ${strategy}`);
        }
      } else if (!unresolved.includes(id)) {
        unresolved.push(id);
      }
    }

    const code = renderRateLimiter(features);

    // really call the static analyzer — the trace is part of the result
    const toolCalls = [];
    const scan = await ctx.callTool?.('static_analyzer', { code });
    if (scan) toolCalls.push(scan);

    const confidence = unresolved.length === 0 ? 0.93 : 0.55;

    return {
      // `unresolved` is a contract with the self-loop: rule ids this agent states it
      // cannot satisfy at all, which decides whether "more budget" is even worth offering
      output: { code, features, appliedFixes: applied, unresolved },
      reasoning:
        `Iteration ${ctx.iteration}: emitted ${code.split('\n').length} lines with ` +
        `${applied.length} feedback-driven repair(s)` +
        (applied.length ? ` [${applied.join('; ')}]` : '') +
        (unresolved.length ? `; no strategy for ${unresolved.join(', ')} → convergence is not reachable.` : '.') +
        ` Static analyzer: ${scan?.success ? `${scan.output?.issueCount ?? 0} issue(s)` : 'unavailable'}.`,
      confidence,
      toolCalls,
      tokensUsed: estimateTokens(code, ctx.criticGuidance ?? '')
    };
  }
}

class CriticBrain implements AgentBrain {
  readonly kind = 'critic';
  readonly name = 'Root-Cause Critic';

  public async think(ctx: BrainContext): Promise<BrainOutput> {
    await latency();
    const failures = (ctx.request.input.failedRules as Array<{ id?: string; message: string }>) ?? [];
    const blocking = (ctx.request.input.blockingReasons as string[]) ?? [];

    const lines: string[] = [];
    lines.push(`ROOT CAUSE ANALYSIS — iteration ${ctx.iteration}`);
    lines.push(`${failures.length} blocking rule(s) remain:`);
    for (const f of failures) {
      const id = f.id ?? 'UNKNOWN';
      const directive = RULE_DIRECTIVES[id] ?? 'no automatic directive available';
      lines.push(`  - ${id}: ${f.message}`);
      lines.push(`      → ${directive}`);
    }
    if (blocking.length > 0) {
      lines.push('Blocking summary:');
      for (const b of blocking.slice(0, 5)) lines.push(`  • ${b}`);
    }
    lines.push('CORRECTIVE PLAN:');
    lines.push('  1. Apply every directive above in a single revision.');
    lines.push('  2. Re-run the sandbox suite; do not regress previously passing assertions.');

    const text = lines.join('\n');

    return {
      output: { feedback: text, directives: failures.map(f => f.id).filter(Boolean) },
      reasoning: text,
      confidence: 0.96,
      tokensUsed: estimateTokens(text)
    };
  }
}

/** Tier-3 auditor brain — reuses the exact deterministic audit implementation. */
export function createAuditBrain(role: string): AgentBrain {
  const checker = auditFor(role);
  return {
    kind: `audit:${role}`,
    name: `Deterministic ${role} audit`,
    async think(ctx: BrainContext): Promise<BrainOutput> {
      const target = String(ctx.request.input.auditTarget ?? '');
      const verdict = checker(target, ctx.request.input.context ?? {});
      return {
        output: verdict,
        reasoning: verdict.comments,
        confidence: verdict.confidence,
        tokensUsed: estimateTokens(target)
      };
    }
  };
}

